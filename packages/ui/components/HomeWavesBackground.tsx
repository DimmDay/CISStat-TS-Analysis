// Декоративный фон главной страницы standalone (шаблон — присланный
// скриншот «Вариант 1. Волны»): мягкий диагональный градиент
// белый → brand-light + два слоя перекрывающихся волн для глубины.
//
// Инлайн SVG, не растровое изображение и не canvas: canvas потребовал бы
// либо JS-перерисовки при каждом ресайзе (ResizeObserver + requestAnimationFrame),
// либо статичного растеризованного кадра фиксированного размера — SVG даёт
// тот же визуальный результат при нулевом весе сети (нет отдельного файла,
// компилируется в тот же JS-чанк) и нулевой стоимости рантайма (браузер
// растягивает векторные path'ы декларативно, без единой строчки
// JS-кода на кадр). Учитывая "минимальным весом, если возможно — canvas" —
// canvas в данном случае не даёт выигрыша по весу против SVG, а добавляет
// сложность и JS-исполнение там, где рисунок статичен, поэтому выбран SVG.
//
// Абсолютно спозиционирован внутри relative-обёртки страницы (не fixed —
// фон должен прокручиваться вместе со страницей, а не быть прибит к
// вьюпорту), decorative (aria-hidden, pointer-events-none), не участвует
// в потоке документа и не мешает читаемости контента поверх.
//
// Прозрачность слоёв волн подобрана с учётом того, что карточки-маршруты
// Hero уже полупрозрачны (bg-brand-light/60, см. RouteCard.tsx) — волны
// заметно светлее (brand-light/45, brand/8%), чтобы не спорить с ними,
// а карточки блока «Возможности» непрозрачны (bg-white) и просто
// «плавают» поверх фона в промежутках между собой.

export function HomeWavesBackground() {
  return (
    <div
      aria-hidden="true"
      className="pointer-events-none absolute inset-0 -z-10 overflow-hidden rounded-2xl bg-gradient-to-br from-white via-white to-brand-light/70"
    >
      <svg
        className="absolute inset-x-0 bottom-0 h-full w-full"
        viewBox="0 0 1000 800"
        preserveAspectRatio="none"
        fill="none"
      >
        <path
          d="M0,260 C180,200 340,340 520,290 C680,250 820,360 1000,300 L1000,800 L0,800 Z"
          className="fill-brand-light/45"
        />
        <path
          d="M0,420 C200,360 380,480 580,430 C740,390 880,470 1000,420 L1000,800 L0,800 Z"
          className="fill-brand/[0.08]"
        />
      </svg>
    </div>
  );
}
