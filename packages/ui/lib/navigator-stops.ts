// на прогресс сессии.
//
// Превью пунктов остановок (items[]) — РЕДУЦИРОВАННАЯ форма (id+title+
// description), короткое описание для правой боковой панели. Полные данные
// (status, count,-violations и т.д.) живут в самих модулях (CHECK_META в
// TsAnalysisValidation.tsx, CHECKS в TsAnalysisPreprocessing.tsx и т.д.),
// к ним идёт обращение при реальном входе в модуль. Здесь — только то, что
// нужно для превью на Навигаторе, без дублирования контракта статусов.

