export interface NavigatorStopItem {
  /** Идентификатор пункта (совпадает с id в CHECK_META/CHECKS соответствующего модуля). */
  id: string;
  /** Короткий заголовок (совпадает с label в соответствующем модуле). */
  title: string;
  /** Короткое описание для превью (1-2 предложения). */
  description: string;
}

export interface NavigatorStop {
  /** Идентификатор остановки (первые 6 — те же, что и в STAGE_DEFS.key). */
  id: string;
  /** Короткая подпись в степпере (ЗАГЛАВНЫМИ, как на макете). */
  label: string;
  /** Подпись этапа одной строкой (под label в степпере). */
  subtitle: string;
  /** Куда ведёт клик по кнопке "Начать анализ" (только для 6 существующих). */
  href: string;
  /** "Скоро" — для 4 будущих остановок. */
  soon?: boolean;
  /** Описание этапа для центрального окна "Описание". */
  description: string;
  /** Превью пунктов для правой боковой панели. */
  items: NavigatorStopItem[];
}

