// render_site, renderer_kind, source_adapter, required refs, view params,
// applicability, caption schema, export status and tests»).
//
// Назначение:
//   - полный denominator научных визуализаций для PNG-экспорта (Путь A)
//     и паспортов/сравнений (Путь B, P01/P02);
//   - источник истины coverage-оракула (visualExportRegistry.coverage.test.ts):
//     unknown/unmapped scientific site блокирует CERT;
//   - JSON-твин config/visual_registry.json — для бэкенда (PGV-01/02) и
//     doc-проверок (scripts/pgv00/check_documents.py); паритет гвардится jest.
//
// Границы PGV-00: реестр — инвентарь и план, НЕ runtime. PNG-рендер,
// VisualResult/VisualPrintSnapshot, producer-адаптеры — PGV-01…09.
// Существующие пути скачивания (ForecastExportMenu legacy PNG, D01–D12
// renditions) не меняются (spec §10.1/§12).

// ── Типы ─────────────────────────────────────────────────────────

export type VisualModuleId =
  | "navigator"
  | "upload"
  | "validation"
  | "preprocessing"
  | "eda"
  | "modeling"
  | "forecasting"
  | "tasks";

export type VisualRendererKind =
  | "recharts_svg" // Recharts/SVG-график (внутренний SVG допустим, PNG-only export, spec §1)
  | "html_table" // научная таблица (previews, матрицы, паспорт, D12)
  | "html_heatmap" // CSS color-scale матрица (пропуски, спектр, отбор признаков)
  | "html_cards" // научные метрики/карточки (счётчики качества, badges, accuracy)
  | "mixed"; // несколько renderer_kind в одном рендер-сайте

export type VisualExportStatus =
  | "planned" // PNG-экспорт запланирован задачами PGV-10…13
  | "legacy_client" // клиентский PNG из первого SVG (ForecastExportMenu); переезд на общий pipeline — PGV-12
  | "not_mounted"; // компонент существует, в UI v1 не смонтирован (честная маркировка, spec §3.6)

export interface VisualSiteRecord {
  /** Канонический идентификатор вида: <module>.<stop>.<view>. */
  view_id: string;
  module_id: VisualModuleId;
  /** Остановка: ветка модуля / пункт Навигатора / группа вида. */
  stop_id: string;
  /** Файл и опорная ветка рендера: "<repo-path>#<branch>". */
  render_site: string;
  /** Переиспользуемый renderer-компонент для печати (PGV-07), если отделён от mount-файла. */
  renderer_component?: string;
  /** Где смонтирован рендер-сайт (оркестратор/страница) — для ручной навигации. */
  mounted_at?: string;
  renderer_kind: VisualRendererKind;
  /** Planned producer-адаптер (PGV-03/04/13) — «pgv-XX/<adapter>». */
  source_adapter: string;
  /** Metadata, обязательные для print snapshot (spec §6: context/revision/target/date/…). */
  required_refs: string[];
  /** Параметры вида, фиксируемые при freeze (zoom/window/selection/entity/…). */
  view_params: string[];
  /** Область применимости: univariate / panel / univariate+panel / static_demo. */
  applicability: string;
  /** Версионированная схема подписи: pgv.caption/<family>/<n>. */
  caption_schema: string;
  export_status: VisualExportStatus;
  /** Тесты, закрепляющие запись (компонентные + coverage-оракул PGV-00). */
  tests: string[];
  /** Существенные оговорки (legacy, not_mounted, reused checkpoint и т.п.). */
  notes?: string;
}

export interface VisualExclusionRecord {
  /** Файл(ы) или glob-шаблон ("packages/ui/components/*Pipeline.tsx"). */
  targets: string[];
  /** Класс причины: decorative / ops_admin / controls / interactive_editor / operational_list / placeholder_soon. */
  reason_class: string;
  /** Явная причина исключения (spec §5: «Decoration exclusions имеют причины»). */
  reason: string;
}

