export interface VisualRegistrySummary {
  schema_version: string;
  total: number;
  modules: Record<VisualModuleId, number>;
  renderer_kinds: Record<VisualRendererKind, number>;
  export_statuses: Record<VisualExportStatus, number>;
}

/** Сводка реестра — denominator coverage для документа инвентаря и CERT. */
export function visualRegistrySummary(): VisualRegistrySummary {
  const modules = Object.fromEntries(VISUAL_MODULE_IDS.map((m) => [m, 0])) as Record<VisualModuleId, number>;
  const rendererKinds = Object.fromEntries(VISUAL_RENDERER_KINDS.map((k) => [k, 0])) as Record<VisualRendererKind, number>;
  const exportStatuses = Object.fromEntries(VISUAL_EXPORT_STATUSES.map((s) => [s, 0])) as Record<VisualExportStatus, number>;
  for (const site of VISUAL_SITE_REGISTRY) {
    modules[site.module_id] += 1;
    rendererKinds[site.renderer_kind] += 1;
    exportStatuses[site.export_status] += 1;
  }
  return {
    schema_version: PGV_REGISTRY_SCHEMA_VERSION,
    total: VISUAL_SITE_REGISTRY.length,
    modules,
    renderer_kinds: rendererKinds,
    export_statuses: exportStatuses,
  };
}

/** Сериализация реестра для JSON-твина (config/visual_registry.json). */
export function serializeVisualRegistry(): {
  schema_version: string;
  generated_from: string;
  pgv_task: string;
  modules: Record<VisualModuleId, number>;
  total_sites: number;
  sites: VisualSiteRecord[];
  exclusions: VisualExclusionRecord[];
} {
  return {
    schema_version: PGV_REGISTRY_SCHEMA_VERSION,
    generated_from: "packages/ui/lib/visualExportRegistry.ts",
    pgv_task: "PGV-00",
    modules: visualRegistrySummary().modules,
    total_sites: VISUAL_SITE_REGISTRY.length,
    sites: VISUAL_SITE_REGISTRY,
    exclusions: VISUAL_RENDER_SITE_EXCLUSIONS,
  };
}

