from openpyxl import Workbook
from openpyxl.styles import Font, Alignment, PatternFill, Border, Side

wb = Workbook()
thin = Border(*[Side(style="thin", color="B0B0B0")]*4)
HDR = PatternFill("solid", fgColor="1F3864"); SEC = PatternFill("solid", fgColor="D6E4F0")
NEW = PatternFill("solid", fgColor="C6EFCE"); MOD = PatternFill("solid", fgColor="FFE0B2")
REM = PatternFill("solid", fgColor="FFC7CE"); NOTE = PatternFill("solid", fgColor="FFF2CC")

def sheet(ws, headers, rows, widths):
    ws.append(headers)
    for c in range(1, len(headers)+1):
        cl = ws.cell(row=1, column=c); cl.font = Font(bold=True, color="FFFFFF")
        cl.fill = HDR; cl.alignment = Alignment(wrap_text=True, vertical="center"); cl.border = thin
    n = 0
    for item in rows:
        if len(item) == 1:
            ws.append([item[0]] + [""]*(len(headers)-1)); r = ws.max_row
            ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=len(headers))
            c1 = ws.cell(row=r, column=1); c1.font = Font(bold=True, color="1F3864"); c1.fill = SEC
            for c in range(1, len(headers)+1): ws.cell(row=r, column=c).border = thin
            continue
        n += 1; ws.append([n]+list(item)); r = ws.max_row
        for c in range(1, len(headers)+1):
            cl = ws.cell(row=r, column=c); cl.border = thin
            cl.alignment = Alignment(vertical="top", wrap_text=True, horizontal="center" if c == 1 else "left")
        ch = item[3]
        fill = NEW if ("НОВОЕ" in item[0] or "Добавле" in ch) else REM if "Удален" in ch else MOD if ("Расширен" in ch or "Усилен" in ch or "Количествен" in ch or "Детализ" in ch) else NOTE
        ws.cell(row=r, column=5).fill = fill
    from openpyxl.utils import get_column_letter
    for i, w in enumerate(widths, 1): ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"

