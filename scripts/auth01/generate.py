#!/usr/bin/env python3
"""Pydantic/OpenAPI -> TS DTOs + camelCase legacy UX adapter, deterministic.

--check is read-only. No FastAPI/scientific imports, no npm/network generation.
Unsupported schema constructs fail generation instead of silently becoming any.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from apps.api.access_registry import REGISTRY, contract_openapi, validate_inventory
from apps.api.plans import INTERNAL_CAPABILITIES, PLAN_DEFINITIONS, PlanName, Role


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def camel(name):
    return re.sub(r"_([a-z])", lambda m:m[1].upper(), name)


def ts_type(schema, *, camel_keys=False):
    if "$ref" in schema:
        name=schema["$ref"].split("/")[-1]
        return name + ("UX" if camel_keys else "DTO")
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(s, camel_keys=camel_keys) for s in schema["anyOf"])
    kind=schema.get("type")
    if kind in ("string", "boolean", "null"):
        return kind
    if kind in ("integer", "number"):
        return "number"
    if kind == "array":
        return "Array<" + ts_type(schema["items"], camel_keys=camel_keys) + ">"
    if kind == "object":
        if "properties" in schema:
            required=set(schema.get("required", []))
            return "{\n" + "\n".join("  " + (camel(k) if camel_keys else k)
                + (":" if k in required else "?:") + " " + ts_type(v, camel_keys=camel_keys) + ";"
                for k,v in schema["properties"].items()) + "\n}"
        if isinstance(schema.get("additionalProperties"), dict):
            return "Record<string, " + ts_type(schema["additionalProperties"], camel_keys=camel_keys) + ">"
    raise ValueError("Unsupported OpenAPI schema: " + repr(schema))


def camel_value(value):
    if isinstance(value, dict):
        return {camel(k):camel_value(v) for k,v in value.items()}
    if isinstance(value, list):
        return [camel_value(v) for v in value]
    return value


def generated_files():
    document=contract_openapi()
    schemas=document["components"]["schemas"]
    lines=["// GENERATED by python scripts/auth01/generate.py --write. DO NOT EDIT.",
           "// UX metadata only; functional_allowed is never auth/object/budget admission.", ""]
    for name,schema in sorted(schemas.items()):
        lines.append(f"export type {name}DTO = {ts_type(schema)};\n")
    for name in ("BaselineLimits", "Capabilities"):
        lines.append(f"export type {name}UX = {ts_type(schemas[name], camel_keys=True)};\n")
    def conversion(name, expression):
        fields = schemas[name]["properties"]
        return "{ " + ", ".join(camel(k) + ": " + (conversion(v["$ref"].split("/")[-1], expression+"."+k)
            if "$ref" in v else expression+"."+k) for k,v in fields.items()) + " }"
    lines += ["export function capabilitiesFromDTO(value: CapabilitiesDTO): CapabilitiesUX {",
              '  if (value.registry_version !== REGISTRY_VERSION || value.capabilities_version !== 2) throw new Error("Unsupported access contract version");',
              "  return " + conversion("Capabilities", "value") + ";", "}"]
    lines += ["export type Role = " + " | ".join(json.dumps(x.value) for x in Role) + ";",
              "export type PlanName = " + " | ".join(json.dumps(x.value) for x in PlanName) + ";",
              "export type OperationId = " + " | ".join(json.dumps(x) for x in REGISTRY.operations) + ";",
              "export const REGISTRY_VERSION = " + json.dumps(REGISTRY.registry_version) + " as const;",
              "export const PLAN_DEFINITIONS: Record<PlanName, CapabilitiesUX> = " + json.dumps({p.value:camel_value(c.model_dump(mode="json")) for p,c in PLAN_DEFINITIONS.items()},ensure_ascii=False,indent=2) + ";",
              "export const INTERNAL_CAPABILITIES: CapabilitiesUX = " + json.dumps(camel_value(INTERNAL_CAPABILITIES.model_dump(mode="json")),indent=2) + ";",
              "export const ACCESS_REGISTRY: AccessRegistryDTO = " + json.dumps(REGISTRY.model_dump(mode="json"),ensure_ascii=False,indent=2) + ";", ""]
    # frozenset is unordered; canonicalize its JSON list to ensure cross-process/OS parity.
    text="\n".join(lines)
    return {"docs/auth01/openapi.json":json_text(document),
            "packages/ui/lib/access-contract.generated.ts":text}


def check(root=ROOT):
    validate_inventory(json.loads((Path(root)/"docs/auth00/inventory.json").read_text(encoding="utf-8")))
    for path,text in generated_files().items():
        target=Path(root)/path
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            raise ValueError("Generated contract drift: " + path)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args=parser.parse_args()
    if args.write:
        for path,text in generated_files().items():
            target=ROOT/path
            target.parent.mkdir(parents=True,exist_ok=True)
            target.write_text(text,encoding="utf-8",newline="\n")
    else:
        check()
    print("AUTH-01 generated OpenAPI/TS parity OK")


if __name__ == "__main__":
    main()
